export function rouletteTranslator(locale: Locale) {
	return createTranslator(ROULETTE_MESSAGES, locale);
}

const BET_LABEL_KEYS: Record<BetType, MessageKey<typeof ROULETTE_MESSAGES>> = {
	straight: 'betStraight',
	red: 'betRed',
	black: 'betBlack',
	odd: 'betOdd',
	even: 'betEven',
	low: 'betLow',
	high: 'betHigh',
	dozen: 'betDozen',
	column: 'betColumn',
};

const DOZEN_ORDINAL_KEYS: Array<MessageKey<typeof ROULETTE_MESSAGES>> = [
	'ordinal1st',
	'ordinal2nd',
	'ordinal3rd',
];

/** Localized bet label ("Straight 17", "Red", "第3列", …). */
export function getRouletteBetLabel(
	locale: Locale,
	bet: { type: BetType; target?: number },
): string {
	const t = rouletteTranslator(locale);
	const key = BET_LABEL_KEYS[bet.type];
	if (bet.type === 'straight') return t('betStraight', { number: String(bet.target ?? 0) });
	if (bet.type === 'dozen') {
		return t('betDozen', {
			ordinal: t(DOZEN_ORDINAL_KEYS[bet.target ?? 0] ?? 'ordinal1st'),
		});
	}
	if (bet.type === 'column') {
		// target 0 = top row (3,6,…,36) = 3rd column;
		// target 2 = bottom row (1,4,…,34) = 1st column.
		return t('betColumn', { number: String(3 - (bet.target ?? 0)) });
	}
	return t(key);
}

/** Localized wheel-result color word ("Green", "赤", …). */
export function getRouletteColorLabel(locale: Locale, number: number): string {
	const t = rouletteTranslator(locale);
	if (number === 0) return t('colorGreen');
	return t(RED_NUMBER_KEYS.has(number) ? 'colorRed' : 'colorBlack');
}

const RED_NUMBER_KEYS = new Set([
	1, 3, 5, 7, 9, 12, 14, 16, 18, 19, 21, 23, 25, 27, 30, 32, 34, 36,
]);

/** Signed net chip result ("+350 chips", "−100 chips", "0 chips"). */
export function formatRouletteNet(locale: Locale, value: number): string {
	if (value === 0) return formatChips(0, locale);
	return `${value > 0 ? '+' : '−'}${formatChips(Math.abs(value), locale)}`;
}
