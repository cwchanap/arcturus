const HAND_CATEGORY_KEYS: Record<HandCategory, MessageKey<typeof VIDEO_POKER_MESSAGES>> = {
	'royal-flush': 'categoryRoyalFlush',
	'straight-flush': 'categoryStraightFlush',
	'four-of-kind': 'categoryFourOfKind',
	'full-house': 'categoryFullHouse',
	flush: 'categoryFlush',
	straight: 'categoryStraight',
	'three-of-kind': 'categoryThreeOfKind',
	'two-pair': 'categoryTwoPair',
	'jacks-or-better': 'categoryJacksOrBetter',
	nothing: 'categoryNothing',
};

export function videoPokerTranslator(locale: Locale) {
	return createTranslator(VIDEO_POKER_MESSAGES, locale);
}

/** Localized hand category display name ("Straight Flush", "同花順", …). */
export function getVideoPokerHandLabel(locale: Locale, category: HandCategory): string {
	return createTranslator(VIDEO_POKER_MESSAGES, locale)(HAND_CATEGORY_KEYS[category]);
}

/** Signed net chip result ("+98 chips", "−2 chips", "0 chips"). */
export function formatVideoPokerNet(locale: Locale, value: number): string {
	if (value === 0) return formatChips(0, locale);
	return `${value > 0 ? '+' : '−'}${formatChips(Math.abs(value), locale)}`;
}
