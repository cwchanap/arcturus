import { formatChipBalance } from '../../formatting';
import type { Locale } from '../locale';
import { createTranslator, defineMessages } from '../translate';

/** Signed chip-result phrase: sign plus the localized chip amount. */
const PROFIT_MESSAGES = defineMessages({
	en: { positive: '+{amount} chips', negative: '−{amount} chips', zero: '0 chips' },
	'zh-Hant': { positive: '+{amount} 籌碼', negative: '−{amount} 籌碼', zero: '0 籌碼' },
	'zh-Hans': { positive: '+{amount} 筹码', negative: '−{amount} 筹码', zero: '0 筹码' },
	ja: { positive: '+{amount} チップ', negative: '−{amount} チップ', zero: '0 チップ' },
});

/**
 * Format a signed net chip result ("+1,200 chips", "−400 chips", "0 chips").
 * Replaces the deleted English-only `formatSignedChipResult` with a complete
 * translated phrase; the numeric amount stays locale-aware.
 */
export function formatSignedProfit(value: number, locale: Locale): string {
	if (!Number.isFinite(value)) throw new RangeError('Value must be finite');
	const translate = createTranslator(PROFIT_MESSAGES, locale);
	if (value === 0) return translate('zero');
	return translate(value > 0 ? 'positive' : 'negative', {
		amount: formatChipBalance(Math.abs(value), locale),
	});
}

