const HAND_NAME_KEYS: Record<PokerHandNameKey, MessageKey<typeof POKER_MESSAGES>> = {
	HIGH_CARD: 'handHighCard',
	PAIR: 'handPair',
	TWO_PAIR: 'handTwoPair',
	THREE_OF_A_KIND: 'handThreeOfAKind',
	STRAIGHT: 'handStraight',
	FLUSH: 'handFlush',
	FULL_HOUSE: 'handFullHouse',
	FOUR_OF_A_KIND: 'handFourOfAKind',
	STRAIGHT_FLUSH: 'handStraightFlush',
	ROYAL_FLUSH: 'handRoyalFlush',
};

const RANK_NAME_KEYS: Partial<Record<Card['rank'], MessageKey<typeof POKER_MESSAGES>>> = {
	11: 'rankJack',
	12: 'rankQueen',
	13: 'rankKing',
	14: 'rankAce',
};

const SUIT_NAME_KEYS: Record<Card['suit'], MessageKey<typeof POKER_MESSAGES>> = {
	hearts: 'suitHearts',
	diamonds: 'suitDiamonds',
	clubs: 'suitClubs',
	spades: 'suitSpades',
};

const LANGUAGE_KEYS: Record<Locale, MessageKey<typeof POKER_MESSAGES>> = {
	en: 'languageEnglish',
	'zh-Hant': 'languageTraditionalChinese',
	'zh-Hans': 'languageSimplifiedChinese',
	ja: 'languageJapanese',
};

export function pokerTranslator(locale: Locale) {
	return createTranslator(POKER_MESSAGES, locale);
}

/** Localized hand category label for a closed ranking key ("Full House", "葫蘆", …). */
export function getPokerHandName(locale: Locale, key: PokerHandNameKey): string {
	return createTranslator(POKER_MESSAGES, locale)(HAND_NAME_KEYS[key]);
}

/** Localized accessible card name; rank glyphs stay invariant. */
export function getPokerCardName(locale: Locale, card: Card): string {
	const t = createTranslator(POKER_MESSAGES, locale);
	const rankKey = RANK_NAME_KEYS[card.rank];
	const rank = rankKey ? t(rankKey) : String(card.rank);
	return t('cardName', { rank, suit: t(SUIT_NAME_KEYS[card.suit]) });
}

/** Active-language name for provider prompts ("English", "繁體中文", "日本語", …). */
export function getPokerLanguageName(locale: Locale): string {
	return createTranslator(POKER_MESSAGES, locale)(LANGUAGE_KEYS[locale]);
}
