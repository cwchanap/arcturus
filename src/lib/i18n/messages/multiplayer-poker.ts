const ERROR_KEYS: Record<string, MessageKey<typeof MULTIPLAYER_POKER_MESSAGES>> = {
	BAD_MESSAGE: 'errorBadMessage',
	NOT_YOUR_TURN: 'errorNotYourTurn',
	INVALID_SEAT: 'errorInvalidSeat',
	INVALID_ACTION: 'errorInvalidAction',
	NOT_ENOUGH_PLAYERS: 'errorNotEnoughPlayers',
};

export function multiplayerPokerTranslator(locale: Locale) {
	return createTranslator(MULTIPLAYER_POKER_MESSAGES, locale);
}

/** Localized label for a protocol error code; unknown codes fall back to a generic label. */
export function getMpErrorLabel(locale: Locale, code: string): string {
	const t = createTranslator(MULTIPLAYER_POKER_MESSAGES, locale);
	return t(ERROR_KEYS[code] ?? 'errorUnknown');
}
