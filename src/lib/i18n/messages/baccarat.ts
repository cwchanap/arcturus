export function baccaratTranslator(locale: Locale) {
	return createTranslator(BACCARAT_MESSAGES, locale);
}

const BET_TYPE_KEYS: Record<BetType, MessageKey<typeof BACCARAT_MESSAGES>> = {
	player: 'betPlayer',
	banker: 'betBanker',
	tie: 'betTie',
	playerPair: 'betPlayerPair',
	bankerPair: 'betBankerPair',
};

const WINNER_KEYS: Record<Winner, MessageKey<typeof BACCARAT_MESSAGES>> = {
	player: 'playerWins',
	banker: 'bankerWins',
	tie: 'tieWins',
};

const OUTCOME_KEYS: Record<'win' | 'lose' | 'push', MessageKey<typeof BACCARAT_MESSAGES>> = {
	win: 'outcomeWin',
	lose: 'outcomeLose',
	push: 'outcomePush',
};

export const BACCARAT_BET_VALIDATION_KEYS: Record<
	BetValidationCode,
	MessageKey<typeof BACCARAT_MESSAGES>
> = {
	'invalid-limits': 'errorInvalidLimits',
	'invalid-range': 'errorInvalidRange',
	'out-of-range': 'errorOutOfRange',
};

/** Localized bet type label ("Player", "莊家", …). */
export function getBaccaratBetTypeLabel(locale: Locale, type: BetType): string {
	return createTranslator(BACCARAT_MESSAGES, locale)(BET_TYPE_KEYS[type]);
}

/** Localized winner sentence ("Player Wins!", "莊家獲勝！", …). */
export function getBaccaratWinnerLabel(locale: Locale, winner: Winner): string {
	return createTranslator(BACCARAT_MESSAGES, locale)(WINNER_KEYS[winner]);
}

/** Localized outcome word for result rows ("WIN", "勝", …). */
export function getBaccaratOutcomeLabel(locale: Locale, outcome: 'win' | 'lose' | 'push'): string {
	return createTranslator(BACCARAT_MESSAGES, locale)(OUTCOME_KEYS[outcome]);
}

/** Signed net chip result ("+100 chips", "−100 chips", "0 chips"). */
export function formatBaccaratNet(locale: Locale, value: number): string {
	if (value === 0) return formatChips(0, locale);
	return `${value > 0 ? '+' : '−'}${formatChips(Math.abs(value), locale)}`;
}
