const CATEGORY_KEYS: Record<PaiGowCategory, MessageKey<typeof PAI_GOW_POKER_MESSAGES>> = {
	'five-aces': 'categoryFiveAces',
	'royal-flush': 'categoryRoyalFlush',
	'straight-flush': 'categoryStraightFlush',
	'four-of-kind': 'categoryFourOfKind',
	'full-house': 'categoryFullHouse',
	flush: 'categoryFlush',
	straight: 'categoryStraight',
	'three-of-kind': 'categoryThreeOfKind',
	'two-pair': 'categoryTwoPair',
	pair: 'categoryPair',
	'high-card': 'categoryHighCard',
};

const RANK_NAME_KEYS: Partial<Record<Card['rank'], MessageKey<typeof PAI_GOW_POKER_MESSAGES>>> = {
	11: 'rankJack',
	12: 'rankQueen',
	13: 'rankKing',
	14: 'rankAce',
};

const SUIT_NAME_KEYS: Record<Suit, MessageKey<typeof PAI_GOW_POKER_MESSAGES>> = {
	hearts: 'suitHearts',
	diamonds: 'suitDiamonds',
	clubs: 'suitClubs',
	spades: 'suitSpades',
};

export function paiGowPokerTranslator(locale: Locale) {
	return createTranslator(PAI_GOW_POKER_MESSAGES, locale);
}

/** Localized hand category display name ("Straight Flush", "同花順", …). */
export function getPaiGowCategoryLabel(locale: Locale, category: PaiGowCategory): string {
	return createTranslator(PAI_GOW_POKER_MESSAGES, locale)(CATEGORY_KEYS[category]);
}

/** Localized accessible card name; rank glyphs stay invariant, the Joker is named. */
export function getPaiGowCardName(locale: Locale, card: PaiGowCard): string {
	const t = createTranslator(PAI_GOW_POKER_MESSAGES, locale);
	if (card.rank === 'joker') return t('joker');
	const rankKey = RANK_NAME_KEYS[card.rank];
	const rank = rankKey ? t(rankKey) : String(card.rank);
	return t('cardName', { rank, suit: t(SUIT_NAME_KEYS[card.suit]) });
}

/** Signed net chip result ("+19 chips", "−20 chips", "0 chips"). */
export function formatPaiGowNet(locale: Locale, value: number): string {
	if (value === 0) return formatChips(0, locale);
	return `${value > 0 ? '+' : '−'}${formatChips(Math.abs(value), locale)}`;
}
